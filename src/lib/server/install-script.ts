import { createHash } from "node:crypto";

/**
 * Backend-generated agent installer (served at
 * GET /api/agent/releases/install.sh) and its checksum sidecar.
 *
 * This module is intentionally dependency-free so the script can be generated
 * and syntax-checked outside the Next.js runtime.
 *
 * Escaping notes: `\\n` becomes a literal backslash-n for `printf` inside the
 * rendered script, and `\${…}` becomes a literal `${…}` for bash parameter
 * expansion. Exit codes: 1 root, 2 env/usage, 3 checksum, 4 download, 5 systemd,
 * 6 sudoers validation.
 */
export const INSTALL_SCRIPT_NAME = "install.sh";

export function generateInstallScript(): string {
  return `#!/usr/bin/env bash
# NexOPS agent installer — generated by the NexOPS control plane.
# Installs nexops-agent as an unprivileged systemd service.
set -euo pipefail

log() { printf '[nexops] %s\\n' "$*"; }
err() { printf '[nexops] error: %s\\n' "$*" >&2; }

# --- 1. Preconditions -------------------------------------------------------
if [ "$EUID" -ne 0 ]; then
  err "this installer must be run as root (re-run with sudo)"
  exit 1
fi

if [ -z "\${ENROL_TOKEN:-}" ]; then
  printf 'Missing required env var ENROL_TOKEN.\\n' >&2
  printf 'Usage: sudo ENROL_TOKEN=<token> CONTROL_PLANE_URL=<https://control-plane> [OS=ubuntu|debian] bash install.sh\\n' >&2
  exit 2
fi
if [ -z "\${CONTROL_PLANE_URL:-}" ]; then
  printf 'Missing required env var CONTROL_PLANE_URL.\\n' >&2
  printf 'Usage: sudo ENROL_TOKEN=<token> CONTROL_PLANE_URL=<https://control-plane> [OS=ubuntu|debian] bash install.sh\\n' >&2
  exit 2
fi

# --- 2. OS / architecture detection -----------------------------------------
# OS env wins; otherwise fall back to /etc/os-release.
ID=""
if [ -z "\${OS:-}" ]; then
  if [ -r /etc/os-release ]; then
    . /etc/os-release
    OS="$ID"
  fi
fi
case "\${OS:-}" in
  ubuntu|debian) ;;
  *)
    err "cannot determine OS (detected '\${OS:-}'); set OS=ubuntu|debian explicitly"
    exit 2
    ;;
esac

case "$(uname -m)" in
  x86_64|amd64) ARCH="amd64" ;;
  aarch64|arm64) ARCH="arm64" ;;
  *)
    err "unsupported architecture $(uname -m); need amd64 or arm64"
    exit 2
    ;;
esac

BASE=$(printf '%s' "$CONTROL_PLANE_URL" | sed -e 's|/*$||')
WORKDIR=$(mktemp -d)
trap 'rm -rf "$WORKDIR"' EXIT

# --- 3. Download and verify the agent binary --------------------------------
log "downloading nexops-agent-linux-$ARCH from $BASE"
if ! curl -fsSL --retry 3 --retry-delay 2 \\
    "$BASE/api/agent/releases/nexops-agent-linux-$ARCH" \\
    -o "$WORKDIR/nexops-agent-linux-$ARCH"; then
  err "failed to download agent binary from $BASE/api/agent/releases/ (check CONTROL_PLANE_URL and outbound network access)"
  exit 4
fi
if ! curl -fsSL --retry 3 --retry-delay 2 \\
    "$BASE/api/agent/releases/nexops-agent-linux-$ARCH.sha256" \\
    -o "$WORKDIR/nexops-agent-linux-$ARCH.sha256"; then
  err "failed to download checksum file from $BASE/api/agent/releases/"
  exit 4
fi

if ! (cd "$WORKDIR" && sha256sum -c "nexops-agent-linux-$ARCH.sha256"); then
  err "checksum verification FAILED for nexops-agent-linux-$ARCH; refusing to install"
  exit 3
fi
log "checksum verified"

# --- 4. Unprivileged service account ----------------------------------------
if ! getent group nexops-agent >/dev/null 2>&1; then
  groupadd --system nexops-agent
fi
if ! id -u nexops-agent >/dev/null 2>&1; then
  useradd --system --gid nexops-agent --home-dir /var/lib/nexops \\
    --create-home --shell /usr/sbin/nologin nexops-agent
fi
install -d -m 0755 -o nexops-agent -g nexops-agent /var/lib/nexops
# Legacy cleanup: a superseded agent version kept its credential here; the
# server-side credential was revoked when the old target was removed, so the
# leftover file is dead state that would only confuse a reinstall.
if [ -f /var/lib/nexops/credentials.json ]; then
  rm -f /var/lib/nexops/credentials.json
  log "removed legacy credentials file from a previous agent install"
fi

# --- 5. Install binary and credentials --------------------------------------
# The binary directory is owned by the service account so unprivileged
# self-update can create a same-directory temp file and atomically rename it
# over the running executable. A compromised agent can therefore only replace
# its own binary (it already runs arbitrary code as this user); the trust
# anchor remains the control-plane TLS origin plus the SHA-256 sidecar.
install -d -m 0755 -o nexops-agent -g nexops-agent /var/lib/nexops/bin
# Stage under a dotfile and rename into place: install(1) opens the target with
# O_TRUNC, which fails with ETXTBSY ("Text file busy") while the service is
# running. A same-directory rename swaps the inode atomically, and the running
# process keeps the old binary until the unit restarts.
install -m 0755 -o nexops-agent -g nexops-agent \\
  "$WORKDIR/nexops-agent-linux-$ARCH" /var/lib/nexops/bin/.nexops-agent.new
mv -f /var/lib/nexops/bin/.nexops-agent.new /var/lib/nexops/bin/nexops-agent
log "installed /var/lib/nexops/bin/nexops-agent"
# Legacy cleanup: older installers placed the binary in /usr/local/bin. The
# unit no longer references that path, so remove the stale copy on upgrade.
rm -f /usr/local/bin/nexops-agent
log "removed legacy /usr/local/bin/nexops-agent (if present)"

# 0770 (not 0755): the agent scrubs its one-time ENROL_TOKEN from agent.env
# after first enrolment via an atomic temp-file rename, which requires write
# on the directory. Group write is granted for that; file contents stay
# individually protected (0640 root:nexops-agent).
install -d -m 0770 -o root -g nexops-agent /etc/nexops
ENV_TMP=$(mktemp)
cat > "$ENV_TMP" <<EOF
CONTROL_PLANE_URL=$CONTROL_PLANE_URL
ENROL_TOKEN=$ENROL_TOKEN
OS=$OS
EOF
# 0640, not 0600: the unit runs as User=nexops-agent, so the GROUP needs read
# access or the agent dies on start with "permission denied" and crash-loops.
# After the post-enrol scrub the atomic rename makes the file agent-owned
# (same mode); root can still read it for systemd EnvironmentFile= at boot —
# acceptable trade-off since only non-secret keys remain.
install -m 0640 -o root -g nexops-agent "$ENV_TMP" /etc/nexops/agent.env
rm -f "$ENV_TMP"
log "wrote /etc/nexops/agent.env (0640, root:nexops-agent)"

# --- 6. Privileged apt helper (least privilege) -----------------------------
# apt maintenance needs root, but the agent must not run privileged in general.
# Only this fixed four-subcommand dispatch is reachable via sudo, and it takes
# no user input beyond the subcommand name itself.
install -d -m 0755 -o root -g root /usr/local/libexec
APT_TMP=$(mktemp)
cat > "$APT_TMP" <<'EOF'
#!/bin/sh
# NexOPS privileged apt helper. Whitelisted subcommands only; no user input
# reaches the shell beyond this single dispatch, so option/argument
# injection is structurally impossible.
set -eu
[ "$#" -eq 1 ] || exit 64
case "$1" in
  update)     exec apt-get update -y ;;
  upgrade)    exec env DEBIAN_FRONTEND=noninteractive apt-get upgrade -y ;;
  fix-broken) exec env DEBIAN_FRONTEND=noninteractive apt-get -f install -y ;;
  simulate)   exec apt-get -s -o Debug::NoLocking=1 upgrade ;;
  *)          exit 64 ;;
esac
EOF
install -m 0755 -o root -g root "$APT_TMP" /usr/local/libexec/nexops-apt
rm -f "$APT_TMP"
log "installed /usr/local/libexec/nexops-apt (0755, root:root)"

SUDO_TMP=$(mktemp)
cat > "$SUDO_TMP" <<'EOF'
nexops-agent ALL=(root) NOPASSWD: /usr/local/libexec/nexops-apt
EOF
install -m 0440 -o root -g root "$SUDO_TMP" /etc/sudoers.d/nexops-agent
rm -f "$SUDO_TMP"
if command -v visudo >/dev/null 2>&1; then
  if ! visudo -cf /etc/sudoers.d/nexops-agent; then
    # An invalid sudoers.d drop-in makes EVERY sudo invocation fail, so remove
    # it before aborting or the host loses all sudo access.
    rm -f /etc/sudoers.d/nexops-agent
    err "visudo rejected /etc/sudoers.d/nexops-agent; removed it and aborted"
    exit 6
  fi
  log "validated /etc/sudoers.d/nexops-agent with visudo (0440, root:root)"
else
  log "visudo not found; installed /etc/sudoers.d/nexops-agent unvalidated (0440, root:root)"
fi

# --- 7. systemd unit --------------------------------------------------------
cat > /etc/systemd/system/nexops-agent.service <<'EOF'
[Unit]
Description=NexOPS fleet agent
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=nexops-agent
Group=nexops-agent
EnvironmentFile=/etc/nexops/agent.env
ExecStart=/var/lib/nexops/bin/nexops-agent
Restart=always
RestartSec=5
TimeoutStopSec=30
# Privilege boundary: the agent runs unprivileged as User=nexops-agent (it
# cannot write /usr, /etc, or any system path) and elevates ONLY via the
# audited /usr/local/libexec/nexops-apt sudoers helper (whitelisted
# subcommands, no argument injection). There is deliberately no read-only
# mount-namespace sandbox here: dpkg/apt must write /usr (binaries, libs,
# docs), /etc (conffiles, updated-alternatives) and /var/cache/debconf
# (mkstemp templates) during a real upgrade, so a read-only root would break
# the agent's core feature without adding security beyond the unprivileged
# user + audited sudoers helper. Do not re-add setuid-blocking directives
# either: they prevent sudo from elevating.
ProtectHome=true
PrivateTmp=true
ProtectKernelTunables=true
ProtectKernelModules=true
ProtectControlGroups=true
LockPersonality=true

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
if ! systemctl enable nexops-agent.service; then
  err "failed to enable nexops-agent.service; inspect with: systemctl status nexops-agent.service"
  exit 5
fi
# restart (never start): \`systemctl start\` is a no-op on an already-active
# unit, which would leave the old process running with the old binary/env
# after an upgrade or control-plane change.
if ! systemctl restart nexops-agent.service; then
  err "failed to restart nexops-agent.service; inspect with: journalctl -u nexops-agent.service -n 100"
  exit 5
fi

log "service nexops-agent enabled and (re)started"
log "follow logs with: journalctl -u nexops-agent -f"
log "the agent enrols on first start, then scrubs ENROL_TOKEN from /etc/nexops/agent.env"
exit 0
`;
}

/** SHA-256 sidecar in `sha256sum -c` format for the exact bytes served. */
export function installScriptChecksum(): string {
  const digest = createHash("sha256").update(generateInstallScript(), "utf8").digest("hex");
  return `${digest}  ${INSTALL_SCRIPT_NAME}\n`;
}
